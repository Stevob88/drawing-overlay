// Regenerates sw.js with the full precache list and a content-hash version.
// Run after changing any app file:  npm run build:sw
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const include = ['index.html', 'manifest.webmanifest', 'css', 'js', 'icons', 'vendor'];
const files = [];
const walk = (rel) => {
  const abs = path.join(root, rel);
  if (fs.statSync(abs).isDirectory()) for (const f of fs.readdirSync(abs).sort()) walk(path.join(rel, f));
  else if (!/\.(map|md)$/.test(rel) && !rel.endsWith('LICENSE')) files.push(rel.split(path.sep).join('/'));
};
include.forEach(walk);
const hash = crypto.createHash('sha256');
for (const f of files) hash.update(f).update(fs.readFileSync(path.join(root, f)));
const version = hash.digest('hex').slice(0, 12);
const sw = `// GENERATED by tools/build-sw.mjs - do not edit by hand.
// Offline cache for RoofLine. Only the app's own files are cached; drawings live in IndexedDB.
const VERSION = 'roofline-${version}';
const ASSETS = ['./', ${files.map((f) => `'./${f}'`).join(', ')}];

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(VERSION).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('roofline-') && k !== VERSION).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== location.origin) return; // never touch other origins
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request)));
});
`;
fs.writeFileSync(path.join(root, 'sw.js'), sw);
console.log(`sw.js: ${files.length} files, version ${version}`);
