// Regenerates sw.js with the full precache list and a content-hash version.
// Run after changing any app file:  npm run build:sw
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
// The version shown in the app's footer: the number of commits including the one about to be
// made (so it goes up with every published change), and today's date.
let count = 0;
try { count = Number(execSync('git rev-list --count HEAD', { cwd: root }).toString().trim()) + 1; } catch { /* not a git checkout */ }
const today = new Date().toISOString().slice(0, 10);
fs.writeFileSync(path.join(root, 'js/version.js'), `// GENERATED by tools/build-sw.mjs - do not edit by hand.\nexport const APP_VERSION = { number: ${count}, date: '${today}' };\n`);
const include = ['index.html', 'manifest.webmanifest', 'css', 'js', 'icons', 'vendor'];
const files = [];
const walk = (rel) => {
  const abs = path.join(root, rel);
  if (fs.statSync(abs).isDirectory()) for (const f of fs.readdirSync(abs).sort()) walk(path.join(rel, f));
  else if (!/\.(map|md)$/.test(rel) && !rel.endsWith('LICENSE')) files.push(rel.split(path.sep).join('/'));
};
include.forEach(walk);
const hash = crypto.createHash('sha256');
for (const f of files) hash.update(f).update(fs.readFileSync(path.join(root, f)));
const version = hash.digest('hex').slice(0, 12);
const sw = `// GENERATED by tools/build-sw.mjs - do not edit by hand.
// Offline cache for RoofLine. Only the app's own files are cached; drawings live in IndexedDB.
const VERSION = 'roofline-${version}';
const ASSETS = ['./', ${files.map((f) => `'./${f}'`).join(', ')}];

// cache: 'reload' so a new version never stores stale copies from the browser's HTTP cache
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(VERSION).then((c) => c.addAll(ASSETS.map((u) => new Request(u, { cache: 'reload' })))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('roofline-') && k !== VERSION).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== location.origin) return; // never touch other origins
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request)));
});
`;
fs.writeFileSync(path.join(root, 'sw.js'), sw);
console.log(`sw.js: ${files.length} files, version ${version}; app version ${count} (${today})`);
